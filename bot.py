def _hr_cache_key(symbols: list[str], days: int) -> str:
    payload = {
        "symbols": sorted(symbols),
        "days": int(days),
        "intervals": ["5m", "15m", "60m", "4h"],
        "end_date": os.getenv("HISTORICAL_REPLAY_END_DATE", "").strip() or "now",
        "v": 3,
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()[:16]


def _historical_replay_end_ms() -> int:
    """Replay bitis zaman damgasi (ms).

    HISTORICAL_REPLAY_END_DATE env'i 'YYYY-MM-DD' formatinda set edilirse o
    gunun bitiе÷ anд╠ (23:59:59 UTC) kullanilir; bos veya hatali ise simdiki zaman.

    Boylece tarihsel rejim donemleri secilebilir:
      - 2024-03-31 -> RISK_ON_TREND_UP (BTC ATH)
      - 2022-07-31 -> RISK_OFF_TREND_DOWN (Luna/3AC sonrasi)
      - 2023-10-31 -> CHOP_RANGE (uzun konsolidasyon)
    """
    end_str = os.getenv("HISTORICAL_REPLAY_END_DATE", "").strip()
    if end_str:
        try:
            dt = datetime.strptime(end_str, "%Y-%m-%d").replace(
                hour=23, minute=59, second=59, tzinfo=timezone.utc
            )
            ts = int(dt.timestamp() * 1000)
            log.info("Replay end date: %s -> %d ms", end_str, ts)
            return ts
        except ValueError:
            log.warning("HISTORICAL_REPLAY_END_DATE format hatali (%s), simdi kullanilacak", end_str)
    return int(time.time() * 1000)


def load_historical_replay_data(symbols: list[str], days: int) -> dict:
    symbols = sorted(set(symbols) | {"BTCUSDT", "ETHUSDT"})
    cache_key = _hr_cache_key(symbols, days)
    if HISTORICAL_REPLAY_USE_CACHE and not HISTORICAL_REPLAY_REFRESH_CACHE:
        cached = _safe_read_json(HISTORICAL_REPLAY_CACHE_FILE, {})
        if cached.get("cache_key") == cache_key and isinstance(cached.get("data"), dict):
            log.info("Historical replay cache kullanд╠lд╠yor: %s", HISTORICAL_REPLAY_CACHE_FILE)
            return cached["data"]

    end_ms = _historical_replay_end_ms()
    day_ms = 24 * 60 * 60 * 1000
    # Yuksek-TF feature'lar rolling window gerektirir (MIN_KLINES_4H=55 bar
    # ~9.2 gun 4h verisi). Kisa backtest pencereleri icin daha geriye uzat
    # ki ilk 5m bar'inda bile EMA + return hesaplanabilsin.
    interval_buffer_days = {"5m": 0, "15m": 0, "60m": 3, "4h": 14}
    out: dict[str, dict[str, list]] = {}

    for sym in symbols:
        out[sym] = {}
        for interval in ("5m", "15m", "60m", "4h"):
            extra = interval_buffer_days.get(interval, 0)
            start_ms = end_ms - (int(days) + extra) * day_ms
            log.info("Replay veri indiriliyor: %s %s (gun=%d+%d)", sym, interval, days, extra)
            out[sym][interval] = fetch_historical_klines(sym, interval, start_ms, end_ms)
            log.info("Replay veri: %s %s %d bar", sym, interval, len(out[sym][interval]))

    _safe_write_json(HISTORICAL_REPLAY_CACHE_FILE, {"cache_key": cache_key, "created_at": now_ts(), "data": out})
    return out


def _hr_idx_at(times: list[int], ts: int) -> int:
    return bisect.bisect_right(times, ts) - 1


def _hr_closed_idx_at(times: list[int], decision_bar_open_ts: int, interval: str) -> int:
    """Latest candle fully closed when the current 5m decision bar closes.

    Historical rows are keyed by *open* time. Using ``_hr_idx_at(times, ts)``
    for 15m/1h/4h therefore exposed the full OHLC of a still-open higher-timeframe
    candle. The decision is evaluated at the current 5m close, so a candle is
    usable only when ``open_time + interval <= decision_time``.
    """

    if interval not in _INTERVAL_MS:
        raise ValueError(f"Desteklenmeyen replay interval: {interval}")
    decision_time = int(decision_bar_open_ts) + _INTERVAL_MS["5m"]
    latest_closed_open = decision_time - _INTERVAL_MS[interval]
    return bisect.bisect_right(times, latest_closed_open) - 1


def _hr_ret(closes: list[float], bars: int) -> float:
    return pct(closes[-1], closes[-(bars + 1)]) if len(closes) >= bars + 1 else 0.0


def _hr_session_at(ts_ms: int) -> SessionContext:
    dt = datetime.fromtimestamp(ts_ms / 1000, timezone.utc).astimezone(ZoneInfo("America/New_York"))
    year, day, weekday = dt.year, dt.strftime("%Y-%m-%d"), dt.weekday()
    minutes = dt.hour * 60 + dt.minute
    if weekday >= 5:
        return _SESSION_PROFILES["WEEKEND"]
    if day in US_MARKET_HOLIDAYS.get(year, set()):
        return _SESSION_PROFILES["US_HOLIDAY"]
    close_time = 13 * 60 if day in US_EARLY_CLOSE.get(year, set()) else 16 * 60
    if 9 * 60 + 30 <= minutes < close_time:
        return _SESSION_PROFILES["US_OPEN"]
    if 4 * 60 <= minutes < 9 * 60 + 30 or close_time <= minutes < 20 * 60:
        return _SESSION_PROFILES["US_EXTENDED"]
    return _SESSION_PROFILES["US_CLOSED"]


