def shutdown_resources() -> None:
    global _SHUTDOWN_DONE
    with _SHUTDOWN_LOCK:
        if _SHUTDOWN_DONE:
            return
        _SHUTDOWN_DONE = True
        log.info("Shutdown sinyali alд╠ndд╠, kaynaklar kapatд╠lд╠yor.")
        _STOP_EVENT.set()
        try:
            _STATE_MGR.save()
        except Exception as e:
            log.warning("Shutdown'da state kaydedilemedi: %s", e)
        try:
            _FEATURE_EXECUTOR.shutdown(wait=False, cancel_futures=True)
            _SYMBOL_EXECUTOR.shutdown(wait=False, cancel_futures=True)
        except Exception:
            pass
        try:
            if _UNIFIED_RUNTIME is not None:
                _UNIFIED_RUNTIME.close()
        except Exception:
            pass
        close_http_sessions()


def _signal_handler(*_args) -> None:
    shutdown_resources()
    raise SystemExit(0)


