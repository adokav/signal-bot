def _send_periodic_messages(
    state_mgr: StateManager,
    results: list[dict],
    session_ctx: SessionContext,
    news_ctx: dict,
) -> None:
    """ц√zet ve heartbeat mesajlarд╠."""
    last_summary = state_mgr.get_meta("last_summary_ts", 0)
    if SEND_SUMMARY_MESSAGES and now_ts() - last_summary >= SUMMARY_INTERVAL_SECONDS:
        if results:
            send_message(make_summary(results, session_ctx, news_ctx))
        # results boе÷ olsa bile ts ilerletilsin ki bir sonraki dilim
        # SUMMARY_INTERVAL kadar sonraya kaysд╠n (dakika dakika tekrar denemesin).
        state_mgr.set_meta("last_summary_ts", now_ts())

    # Decision-change heartbeat:
    # Default mode sends Telegram status only when the practical bot decision changes.
    # This prevents repeated WAIT/NEUTRAL status messages from spamming Telegram.
    if TELEGRAM_DECISION_CHANGE_ONLY:
        send_report, fingerprint, report_reason = should_send_decision_report(
            state_mgr, results, session_ctx, news_ctx
        )
        if send_report:
            pending_count = len([
                s for s in _suggestions_payload().get("suggestions", [])
                if isinstance(s, dict) and s.get("status") == "PENDING"
            ])
            if TELEGRAM_REPORT_STYLE == "DEBUG" or TELEGRAM_FULL_HEARTBEAT:
                heartbeat_text = format_debug_heartbeat(state_mgr, results, pending_count)
            else:
                heartbeat_text = format_human_heartbeat(state_mgr, results, session_ctx, news_ctx, pending_count)
            send_message(heartbeat_text)
            state_mgr.set_meta("last_telegram_decision_fingerprint", fingerprint)
            state_mgr.set_meta("last_telegram_decision_report_ts", now_ts())
            state_mgr.set_meta("last_telegram_decision_report_reason", report_reason)
            state_mgr.set_meta("last_heartbeat_ts", now_ts())
            state_mgr.save()
        return

    # Legacy periodic heartbeat mode.
    last_heartbeat = state_mgr.get_meta("last_heartbeat_ts", 0)
    if now_ts() - last_heartbeat >= HEARTBEAT_INTERVAL_SECONDS:
        generate_parameter_suggestions_from_weight_learning(state_mgr, notify=True)
        pending_count = len([
            s for s in _suggestions_payload().get("suggestions", [])
            if isinstance(s, dict) and s.get("status") == "PENDING"
        ])
        if TELEGRAM_REPORT_STYLE == "DEBUG" or TELEGRAM_FULL_HEARTBEAT:
            heartbeat_text = format_debug_heartbeat(state_mgr, results, pending_count)
        else:
            heartbeat_text = format_human_heartbeat(state_mgr, results, session_ctx, news_ctx, pending_count)
        send_message(heartbeat_text)
        state_mgr.set_meta("last_heartbeat_ts", now_ts())


